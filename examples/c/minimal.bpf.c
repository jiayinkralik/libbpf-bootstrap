    // ".byte 0x3f, 0x30, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00\n\t"
    // ".byte 0x37, 0x30, 0x01, 0x00, 0xf8, 0x00, 0x00, 0x00\n\t"
    // SMOD
    // ".byte 0x9f, 0x30, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00\n\t"
    // ".byte 0x97, 0x30, 0x01, 0x00, 0xf8, 0x00, 0x00, 0x00\n\t"
    // MOVSX (only defined when source bit = 0; offset = 8/16/32)
    // ".byte 0xbf, 0x30, 0x08, 0x00, 0x00, 0x00, 0x00, 0x00\n\t"
