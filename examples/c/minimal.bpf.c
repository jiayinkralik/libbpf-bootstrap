    // ".byte 0x06, 0x00, 0x00, 0x00, 0x2a, 0x00, 0x00, 0x00\n\t"

    // // JEQ r0, r3, +2
    // ".byte 0x15, 0x03, 0x02, 0x00, 0x00, 0x00, 0x00, 0x00\n\t"

    // // JNE r0, r3, +1
    // ".byte 0x55, 0x03, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00\n\t"

    // // JGT r0, r3, +1
    // ".byte 0x25, 0x03, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00\n\t"

    // // JLT r0, 5, +3
    // ".byte 0xa5, 0x00, 0x03, 0x00, 0x05, 0x00, 0x00, 0x00\n\t"

    // // JGE r0, r3, +1
    // ".byte 0x35, 0x03, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00\n\t"

    // // JSET r0, r3, +1
    // ".byte 0x45, 0x03, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00\n\t"

    // // JSGT r3 > 0, +1
    // ".byte 0x65, 0x03, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00\n\t"

    // // JSGE r3 >= 0, +1
    // ".byte 0x75, 0x03, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00\n\t"

    // // JSLT r3 < 0, +1
    // ".byte 0xc5, 0x03, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00\n\t"

    // // JSLE r3 <= 0, +1
    // ".byte 0xd5, 0x03, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00\n\t"

    // // JLE r3 <= 0, +1 (unsigned)
    // ".byte 0xb5, 0x03, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00\n\t"

    // // === CALL Instructions ===
    
    // // CALL helper 1 (PC-relative)
    // ".byte 0x85, 0x10, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00\n\t"

